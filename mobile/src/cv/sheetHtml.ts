// The A4 sheet as HTML — ONE definition used by both the WebView preview and
// expo-print's PDF, so what the pilot sees is what downloads. Mirrors the web
// CvSheet.jsx markup and the approved mockup; the server decides the content
// and the masking (audience), this only draws it.
//
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Any = any;

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c] as string));

const TITLE: Record<string, string> = {
  experience: 'Flight experience', licences: 'Licences &amp; ratings', medical: 'Medical &amp; English',
  training: 'Training', employment: 'Employment history', rtw: 'Right to work', education: 'Education &amp; languages',
};

function items(list: Any[]): string {
  if (!list?.length) return '<p class="empty">Not on your profile yet.</p>';
  return list.map((it) => `<div class="it"><span class="k">${esc(it.k)}</span><span class="v${it.flag ? ` flag ${it.flag}` : ''}">${esc(it.v)}</span></div>`).join('');
}

function section(key: string, doc: Any, accent: string): string {
  const s = doc.sections[key];
  if (key === 'photo') return '';
  if (key === 'experience') {
    return `<div class="s"><h2 style="color:${accent}">${TITLE[key]}</h2>
      <div class="hrs">${s.stats.map((st: Any) => `<div><b>${esc(st.value)}</b><span>${esc(st.label)}</span></div>`).join('')}</div>
      ${s.note ? `<p class="note">${esc(s.note)}</p>` : ''}</div>`;
  }
  if (key === 'employment' && !s.items.length) return '';
  return `<div class="s"><h2 style="color:${accent}">${TITLE[key]}</h2>${items(s.items)}</div>`;
}

export function cvSheetHtml(doc: Any, { forPrint = false, fitWidth = 0 } = {}): string {
  const accent = doc.accentHex || '#0B1F3A';
  const modern = doc.template === 'modern';
  const contact = [doc.header.base, doc.header.phone, doc.header.email].filter(Boolean).map(esc);
  const photo = doc.order.find((o: Any) => o.key === 'photo' && o.visible) && doc.sections.photo?.url;
  const body = doc.order.filter((o: Any) => o.visible && o.key !== 'photo').map((o: Any) => section(o.key, doc, accent)).join('');
  const summary = doc.summary ? `<div class="s"><h2 style="color:${accent}">Summary</h2><p>${esc(doc.summary)}</p></div>` : '';
  const src = `<div class="src">Generated by CockpitHire from the pilot's profile and logbook.</div>`;

  const inner = modern ? `
    <div class="modern">
      <aside style="background:${accent}">
        ${photo ? `<img class="photo" src="${esc(doc.sections.photo.url)}">` : ''}
        <div class="mname">${esc(doc.header.name)}</div>
        ${doc.header.headline ? `<div class="mhl">${esc(doc.header.headline)}</div>` : ''}
        <div class="mct">${contact.map((c) => `<div>${c}</div>`).join('')}</div>
      </aside>
      <div class="main">${summary}${body}${src}</div>
    </div>`
    : `
    ${photo ? `<img class="photo classic" src="${esc(doc.sections.photo.url)}">` : ''}
    <div class="h" style="border-bottom-color:${accent}">
      <div><h1>${esc(doc.header.name)}</h1>${doc.header.headline ? `<div class="hl">${esc(doc.header.headline)}</div>` : ''}</div>
      <div class="ct">${contact.map((c) => `<div>${c}</div>`).join('')}</div>
    </div>${summary}${body}${src}`;

  // forPrint: expo-print lays the page out itself, so the sheet fills the page
  // and carries no shadow. On screen the sheet is drawn at its true A4 pixel
  // size and scaled to the box — a viewport meta scale is ignored inside the
  // web target's iframe, a transform is honoured everywhere.
  const k = fitWidth ? fitWidth / 794 : 1;
  const fit = fitWidth ? `html,body{width:${794 * k}px;height:${1123 * k}px;overflow:hidden}
  .sheet{transform:scale(${k});transform-origin:0 0;box-shadow:none}` : '';
  return `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=794, initial-scale=1">
<style>
  @page { size: A4; margin: 0; }
  *{box-sizing:border-box}
  body{margin:0;background:#fff;-webkit-font-smoothing:antialiased;
       font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif;color:#141A24}
  .sheet{width:794px;min-height:1123px;margin:0 auto;background:#fff;padding:${modern ? '0' : '56px 60px'};
         font-size:12.5px;line-height:1.5;${forPrint ? '' : 'box-shadow:0 2px 10px rgba(15,27,45,.10);'}overflow:hidden}
  h1{font-family:Georgia,serif;font-weight:600;font-size:32px;margin:0;letter-spacing:-.01em}
  .h{display:flex;justify-content:space-between;align-items:flex-end;border-bottom:2px solid;padding-bottom:16px}
  .hl{font-size:14px;color:#3A4658;margin-top:4px}
  .ct{text-align:right;font-size:11.5px;color:#3A4658;line-height:1.7}
  .s{margin-top:22px}
  .s h2{font-size:10.5px;letter-spacing:.14em;text-transform:uppercase;margin:0 0 9px;font-weight:700}
  .s p{margin:0}
  .hrs{display:grid;grid-template-columns:repeat(3,1fr);border:1px solid #DCE2EA;border-radius:6px}
  .hrs div{padding:10px 12px;border-left:1px solid #DCE2EA}
  .hrs div:first-child{border-left:0}
  .hrs b{display:block;font-family:Georgia,serif;font-size:19px;font-weight:600;font-variant-numeric:tabular-nums}
  .hrs span{font-size:10.5px;color:#5A6576}
  .note,.empty{font-size:10.5px;color:#8592A3;margin-top:6px}
  .it{display:flex;justify-content:space-between;gap:12px;padding:5px 0;border-bottom:1px solid #EEF1F5}
  .it:last-child{border-bottom:0}
  .it .k{font-weight:600}
  .it .v{color:#4A5668;text-align:right}
  .it .v.flag.red{color:#B42318;font-weight:600}
  .it .v.flag.amber{color:#B45309}
  .photo{width:92px;height:92px;object-fit:cover;border-radius:6px;display:block}
  .photo.classic{margin:0 0 16px auto}
  .modern{display:grid;grid-template-columns:232px 1fr;min-height:1123px}
  .modern aside{color:#fff;padding:44px 24px}
  .modern .photo{width:100%;height:auto;aspect-ratio:1;margin-bottom:16px}
  .mname{font-family:Georgia,serif;font-size:24px;font-weight:600;line-height:1.2}
  .mhl{font-size:12.5px;opacity:.85;margin-top:8px}
  .mct{font-size:11.5px;opacity:.8;margin-top:18px;line-height:1.8;word-break:break-word}
  .modern .main{padding:48px 44px}
  .src{font-size:10px;color:#8592A3;margin-top:24px;border-top:1px solid #EEF1F5;padding-top:8px}
  .modern .src{margin:24px 44px 44px}
  ${fit}
</style></head><body><div class="sheet">${inner}</div></body></html>`;
}
