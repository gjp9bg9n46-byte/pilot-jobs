import React from 'react';

/**
 * The A4 sheet. ONE renderer for the builder preview and the public share
 * page, so what the pilot checks is exactly what an airline opens.
 *
 * It renders the server's document verbatim — no data is derived here, and the
 * masking decision was already made server-side (audience). The PDF has its own
 * renderer (CvPdf.jsx) because @react-pdf cannot use DOM layout.
 *
 * Two templates: Classic (full-width, rule under the header) and Modern (accent
 * sidebar). Four accents, passed in as a hex from the palette tokens.
 */

const ACCENT_HEX = { navy: '#0B1F3A', charcoal: '#2E3440', slate: '#3B5672', forest: '#24453A' };
export const ACCENTS = [
  { key: 'navy', label: 'Navy', hex: ACCENT_HEX.navy },
  { key: 'charcoal', label: 'Charcoal', hex: ACCENT_HEX.charcoal },
  { key: 'slate', label: 'Slate', hex: ACCENT_HEX.slate },
  { key: 'forest', label: 'Forest', hex: ACCENT_HEX.forest },
];
export const accentHex = (k) => ACCENT_HEX[k] || ACCENT_HEX.navy;

const SECTION_TITLE = {
  experience: 'Flight experience', licences: 'Licences & ratings', medical: 'Medical & English',
  training: 'Training', employment: 'Employment history', rtw: 'Right to work',
  education: 'Education & languages', photo: 'Photo',
};

function Items({ items }) {
  if (!items?.length) return <p className="cv-empty">Not on your profile yet.</p>;
  return items.map((it, i) => (
    <div className="cv-it" key={`${it.k}-${i}`}>
      <span className="k">{it.k}</span>
      <span className={`v${it.flag ? ` flag ${it.flag}` : ''}`}>{it.v}</span>
    </div>
  ));
}

function Section({ k, doc, accent }) {
  const s = doc.sections[k];
  if (k === 'photo') return s?.url ? <img className="cv-photo" src={s.url} alt="" /> : null;
  if (k === 'experience') {
    return (
      <div className="cv-s" key={k}>
        <h2 style={{ color: accent }}>{SECTION_TITLE[k]}</h2>
        <div className="cv-hrs">
          {s.stats.map((st) => <div key={st.label}><b>{st.value}</b><span>{st.label}</span></div>)}
        </div>
        {s.note && <p className="cv-note">{s.note}</p>}
      </div>
    );
  }
  if (k === 'employment' && !s.items.length) return null;
  return (
    <div className="cv-s" key={k}>
      <h2 style={{ color: accent }}>{SECTION_TITLE[k]}</h2>
      <Items items={s.items} />
    </div>
  );
}

export default function CvSheet({ doc, scale }) {
  if (!doc) return null;
  const accent = doc.accentHex || accentHex(doc.accent);
  const visible = doc.order.filter((o) => o.visible && o.key !== 'photo');
  const photo = doc.order.find((o) => o.key === 'photo' && o.visible) && doc.sections.photo?.url;
  const modern = doc.template === 'modern';
  const contact = [doc.header.base, doc.header.phone, doc.header.email].filter(Boolean);

  const head = (
    <div className={`cv-h${modern ? ' m' : ''}`} style={modern ? undefined : { borderBottomColor: accent }}>
      <div>
        <h1>{doc.header.name}</h1>
        {doc.header.headline && <div className="hl">{doc.header.headline}</div>}
      </div>
      <div className="ct">{contact.map((c, i) => <div key={i}>{c}</div>)}</div>
    </div>
  );

  const body = visible.map((o) => <Section key={o.key} k={o.key} doc={doc} accent={accent} />);

  return (
    <div className={`cv-sheet${modern ? ' modern' : ''}`} style={scale ? { transform: `scale(${scale})`, transformOrigin: '0 0' } : undefined}>
      {modern ? (
        <div className="cv-modern">
          <aside style={{ background: accent }}>
            {photo && <img className="cv-photo" src={doc.sections.photo.url} alt="" />}
            <div className="mname">{doc.header.name}</div>
            {doc.header.headline && <div className="mhl">{doc.header.headline}</div>}
            <div className="mct">{contact.map((c, i) => <div key={i}>{c}</div>)}</div>
          </aside>
          <div className="cv-main">
            {doc.summary && <div className="cv-s"><h2 style={{ color: accent }}>Summary</h2><p>{doc.summary}</p></div>}
            {body}
          </div>
        </div>
      ) : (
        <>
          {photo && <img className="cv-photo classic" src={doc.sections.photo.url} alt="" />}
          {head}
          {doc.summary && <div className="cv-s"><h2 style={{ color: accent }}>Summary</h2><p>{doc.summary}</p></div>}
          {body}
        </>
      )}
      <div className="cv-src">Generated by CockpitHire from the pilot's profile and logbook.</div>
    </div>
  );
}
